export interface IconShape {
  tag: 'path' | 'circle' | 'line' | 'polyline' | 'polygon' | 'rect';
  attrs: Record<string, string>;
}

function parse(markup: string): IconShape[] {
  const shapes: IconShape[] = [];
  for (const [, tag, rawAttrs] of markup.matchAll(/<(\w+)([^>]*)\/>/g)) {
    const attrs: Record<string, string> = {};
    for (const [, key, value] of rawAttrs.matchAll(/([\w-]+)="([^"]*)"/g)) attrs[key] = value;
    shapes.push({ tag: tag as IconShape['tag'], attrs });
  }
  return shapes;
}

